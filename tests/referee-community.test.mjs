import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
test('community exposes opt-in state and name only; portal feedback reaches only developers',async()=>{
 const db=new PGlite();try{
 await db.exec(`create schema auth;create role anon;create role authenticated;create table auth.users(id uuid primary key);create table events(id uuid primary key,name text);
 create function auth.uid() returns uuid language sql as $$select current_setting('test.uid',true)::uuid$$;
 create function auth.jwt() returns jsonb language sql as $$select jsonb_build_object('is_anonymous',current_setting('test.anon',true),'email','ref@example.org')$$;
 grant usage on schema auth to authenticated;grant execute on all functions in schema auth to authenticated;
 create table event_members(user_id uuid,role text,developer boolean);
 create table field_log(id uuid,event_id uuid,session_id uuid,kind text,note text,logged_by text,created_at timestamptz);
 create table league_sessions(id uuid,name text);
 create table feedback_management(feedback_id uuid primary key,status text,updated_at timestamptz);`);
 await db.exec(await readFile(new URL('../supabase/referee-portal.sql',import.meta.url),'utf8'));
 await db.exec(await readFile(new URL('../supabase/referee-community.sql',import.meta.url),'utf8'));
 const a='22222222-2222-4222-8222-222222222222',b='33333333-3333-4333-8333-333333333333',id='44444444-4444-4444-8444-444444444444';
 await db.query('insert into auth.users values ($1),($2)',[a,b]);
 await db.query("select set_config('test.uid',$1,false),set_config('test.anon','false',false)",[a]);await db.exec('set role authenticated');
 await db.query("insert into referee_profiles(user_id,full_name,country,region,city,phone,map_name,map_visible) values ($1,'Alex Smith','United States','New Jersey','Private city','Private phone','Alex',false)",[a]);
 assert.deepEqual((await db.query('select * from list_referee_map()')).rows,[]);
 await db.query('update referee_profiles set map_visible=true where user_id=$1',[a]);
 await db.query("select set_config('test.uid',$1,false)",[b]);
 assert.deepEqual((await db.query('select * from list_referee_map()')).rows,[{display_name:'Alex',state:'New Jersey'}]);
 assert.equal((await db.query('select * from referee_profiles')).rows.length,0);
 await db.query('select submit_referee_portal_feedback($1,$2,$3)',[id,'bug','A portal issue']);
 await db.query('select submit_referee_portal_feedback($1,$2,$3)',[id,'bug','Duplicate retry']);
 await assert.rejects(db.query('select * from referee_portal_feedback'),/permission denied/);
 await assert.rejects(db.query('select * from list_universal_feedback()'),/Developer access required/);
 await db.exec('reset role');await db.query("insert into event_members values ($1,'admin',true)",[a]);
 await db.query("select set_config('test.uid',$1,false)",[a]);await db.exec('set role authenticated');
 let feedback=(await db.query('select * from list_universal_feedback()')).rows;
 assert.equal(feedback.length,1);assert.equal(feedback[0].event_name,'Referee portal');assert.equal(feedback[0].note,'[bug] A portal issue');
 await db.query('select set_universal_feedback_status($1,$2)',[id,'resolved']);
 assert.equal((await db.query('select * from list_universal_feedback()')).rows[0].status,'resolved');
 await db.query('update referee_profiles set map_visible=false where user_id=$1',[a]);
 assert.deepEqual((await db.query('select * from list_referee_map()')).rows,[]);
 await db.query("select set_config('test.anon','true',false)");
 await assert.rejects(db.query('select * from list_referee_map()'),/Referee account required/);
 }finally{await db.close();}
});
