import {mkdirSync,readdirSync,statSync,copyFileSync,renameSync,unlinkSync,existsSync} from 'node:fs';
import {join,resolve,sep} from 'node:path';
import {randomBytes} from 'node:crypto';
import {DatabaseSync} from 'node:sqlite';

const backupName=/^venue-\d{13}-[a-f0-9]{8}\.sqlite$/;
export function backups(dataDir){const dir=join(dataDir,'backups');if(!existsSync(dir))return [];return readdirSync(dir).filter(n=>backupName.test(n)).map(name=>({name,time:statSync(join(dir,name)).mtimeMs,bytes:statSync(join(dir,name)).size})).sort((a,b)=>b.time-a.time);}
export function makeBackup(store,dataDir){
 const dir=join(dataDir,'backups');mkdirSync(dir,{recursive:true});
 const name=`venue-${Date.now()}-${randomBytes(4).toString('hex')}.sqlite`,target=join(dir,name);
 store.db.exec(`VACUUM INTO '${target.replaceAll("'","''")}'`);
 // Only files generated by this app inside its backup folder are eligible for rotation.
 for(const old of backups(dataDir).slice(24))unlinkSync(join(dir,old.name));
 return name;
}
export function restoreBackup(dataDir,name){
 if(!backupName.test(name)||!backups(dataDir).some(b=>b.name===name))throw Error('Choose a saved venue backup.');
 const dir=resolve(dataDir,'backups'),source=resolve(dir,name);if(!source.startsWith(dir+sep))throw Error('Invalid backup path.');
 const check=new DatabaseSync(source,{readOnly:true});
 try{if(check.prepare('PRAGMA quick_check').get().quick_check!=='ok')throw Error('Backup integrity check failed.');check.prepare('SELECT event_id FROM venue_events LIMIT 1').all();}finally{check.close();}
 const current=join(dataDir,'refos-venue.sqlite'),temp=join(dataDir,'restore-pending.sqlite');copyFileSync(source,temp);
 if(existsSync(current)){
  const db=new DatabaseSync(current);try{makeBackup({db},dataDir);}finally{db.close();}
 }
 // The host must be stopped before calling this function; no connections may use these files.
 for(const suffix of ['-wal','-shm'])if(existsSync(current+suffix))unlinkSync(current+suffix);
 renameSync(temp,current);
}
export function hostDevices(store,now=Date.now()){
 if(!store)return [];
 return store.listEvents().flatMap(event=>store.listDevices(event.event_id).map(d=>({eventId:event.event_id,id:d.device_id,name:d.label||'Unnamed device',lastSeen:d.last_seen,lastSeq:d.last_seq||0,online:now-d.last_seen<90000})));
}
export function readiness({health,addresses,devices,events,backupError}){
 const active=devices.filter(d=>d.online),counts=new Map();for(const d of active)if(d.lastSeq>0)counts.set(d.eventId,(counts.get(d.eventId)||0)+1);
 return [
  {label:'Server responds',ok:health,help:health?'Local server is responding.':'Start the server, then check again.'},
  {label:'Network address available',ok:addresses.length>0,help:addresses.length?'Use the QR code on another device on this Wi-Fi.':'Connect the host to venue Wi-Fi.'},
  {label:'Event signed in and paired',ok:events>0,help:events?'At least one event has paired with this server.':'Open Ref OS at the venue address and sign in while internet is available.'},
  {label:'Two devices received shared data',ok:[...counts.values()].some(n=>n>=2),help:'Connect two devices to the same event, add a sample violation, and wait for both devices to sync. This checks their sync acknowledgments; it cannot test every device or Wi-Fi route.'},
  {label:'Automatic backups available',ok:!backupError,help:backupError||'A backup is saved at startup, every 5 minutes, and before stopping. The latest 24 are kept.'}
 ];
}
